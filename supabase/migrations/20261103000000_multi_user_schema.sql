-- Multi-user schema: unfiltered job_postings, per-user applicant profiles,
-- server-side matching, and a private resumes bucket.
--
-- The hand-made placeholder tables (empty on 2026-11-03) were renamed to
-- job_postings_old / applicant_old before this ran; drop them once unneeded.
alter table if exists public.job_postings rename to job_postings_old;
alter table if exists public.applicant rename to applicant_old;

-- ---------------------------------------------------------------------------
-- job_postings: every scraped job, unfiltered. Written only by the scraper
-- (secret key / service_role); readable by anyone.
-- ---------------------------------------------------------------------------
create table public.job_postings (
  id             bigint generated by default as identity primary key,
  dedupe_key     text        not null unique,   -- "company|title", or the URL
  title          text        not null,
  company        text,
  location       text,
  remote         boolean     not null default false,
  salary         text,
  url            text        not null,
  description    text,                          -- full text, HTML stripped
  posted_date    date,
  years_required smallint,                      -- lowest "N+ years" found in the text
  source         text        not null,
  created_at     timestamptz not null default now(),  -- first seen
  last_seen_at   timestamptz not null default now()   -- refreshed on every scrape that returns it
);
create index job_postings_posted_idx
  on public.job_postings (coalesce(posted_date, (created_at at time zone 'utc')::date) desc);
create index job_postings_last_seen_idx on public.job_postings (last_seen_at);

alter table public.job_postings enable row level security;
create policy "Job postings are public" on public.job_postings
  for select to anon, authenticated using (true);

-- ---------------------------------------------------------------------------
-- applicant: one row per user, built from their resume.
-- ---------------------------------------------------------------------------
create table public.applicant (
  id                     bigint generated by default as identity primary key,
  user_id                uuid unique references auth.users (id) on delete cascade,
  email                  text unique,           -- links a pre-seeded row to the account on first sign-in
  name                   text,
  headline               text,                  -- one-line summary of the resume
  years_experience       numeric(4,1),
  target_roles           text[]   not null default '{}',   -- job titles to search for
  locations              jsonb    not null default '[]',   -- [{"city","country","country_code"}]
  open_to_remote         boolean  not null default true,
  remote_allowed_regions text[]   not null default '{worldwide,anywhere,global}',
  skills                 jsonb    not null default '{}',   -- {"java": 3, "sql": 1}
  title_include          text[]   not null default '{}',
  title_exclude          text[]   not null default '{}',
  max_years_required     smallint,
  min_score              smallint not null default 1,
  max_days_old           smallint default 7,    -- default for the UI's "Posted within"
  resume_path            text,                  -- object path in the "resumes" bucket
  resume_parsed_at       timestamptz,
  created_at             timestamptz not null default now(),
  updated_at             timestamptz not null default now()
);

alter table public.applicant enable row level security;
create policy "Applicants read their own row" on public.applicant
  for select to authenticated using ((select auth.uid()) = user_id);
create policy "Applicants update their own row" on public.applicant
  for update to authenticated
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "Applicants delete their own row" on public.applicant
  for delete to authenticated using ((select auth.uid()) = user_id);
-- Rows are created by the parse-resume Edge Function (service role). From the
-- browser, users may only edit their preferences, never user_id / email.
revoke insert, update on public.applicant from anon, authenticated;
grant update (name, headline, years_experience, target_roles, locations, open_to_remote,
              remote_allowed_regions, skills, title_include, title_exclude,
              max_years_required, min_score, max_days_old)
  on public.applicant to authenticated;

create or replace function public.touch_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  return new;
end $$;
create trigger applicant_touch_updated_at before update on public.applicant
  for each row execute function public.touch_updated_at();

-- When someone signs up with the email of a pre-seeded applicant, claim that row.
create or replace function public.link_applicant_to_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  update public.applicant set user_id = new.id
   where user_id is null and lower(email) = lower(new.email);
  return new;
end $$;
revoke execute on function public.link_applicant_to_user() from public, anon, authenticated;
create trigger on_auth_user_created_link_applicant after insert on auth.users
  for each row execute function public.link_applicant_to_user();

-- ---------------------------------------------------------------------------
-- Scraper ingest: insert new postings, bump last_seen_at on known ones.
-- Returns which keys were newly inserted. Service role only.
-- ---------------------------------------------------------------------------
create or replace function public.ingest_jobs(jobs jsonb)
returns table (dedupe_key text, inserted boolean)
language sql volatile set search_path = '' as $$
  insert into public.job_postings as jp
    (dedupe_key, title, company, location, remote, salary, url, description,
     posted_date, years_required, source)
  select x.dedupe_key, x.title, x.company, x.location, coalesce(x.remote, false), x.salary,
         x.url, x.description, x.posted_date, x.years_required, x.source
  from jsonb_to_recordset(jobs) as x(
    dedupe_key text, title text, company text, location text, remote boolean, salary text,
    url text, description text, posted_date date, years_required smallint, source text)
  on conflict on constraint job_postings_dedupe_key_key do update set last_seen_at = now()
  returning jp.dedupe_key, (xmax = 0) as inserted
$$;
revoke execute on function public.ingest_jobs(jsonb) from public, anon, authenticated;
grant execute on function public.ingest_jobs(jsonb) to service_role;

-- ---------------------------------------------------------------------------
-- Matching: score every posting against the signed-in user's applicant row.
-- ---------------------------------------------------------------------------
-- Regex for a whole-term match: "java" must not match "javascript", and
-- "c++" / "node.js" / "ci/cd" are matched literally.
create or replace function public.term_pattern(term text)
returns text language sql immutable parallel safe set search_path = '' as $$
  select '(^|[^a-z0-9])' || regexp_replace(lower(term), '([^a-z0-9 ])', '\\\1', 'g') || '($|[^a-z0-9])'
$$;

create or replace function public.match_jobs(
  p_max_days int default null,
  p_include_ineligible boolean default false,
  p_limit int default 500)
returns table (
  id bigint, title text, company text, location text, remote boolean, salary text, url text,
  description_snippet text, posted_date date, first_seen timestamptz, source text,
  years_required smallint, score int, matched_skills text[], remote_ok boolean,
  eligible boolean, reasons text[])
language sql stable security invoker set search_path = '' as $$
with me as (
  select * from public.applicant where user_id = (select auth.uid())
),
skills as (
  select s.key as skill, s.value::int as weight, public.term_pattern(s.key) as pat
  from me, jsonb_each_text(me.skills) s
),
cities as (
  select lower(p->>'city') as city
  from me, jsonb_array_elements(me.locations) p
  where coalesce(p->>'city', '') <> ''
),
scored as (
  select j.*, me.title_include, me.title_exclude, me.max_years_required, me.min_score,
         me.open_to_remote, jsonb_array_length(me.locations) as n_locations,
         sk.score, sk.matched,
         exists (select 1 from unnest(me.title_include) x
                  where lower(j.title) ~ public.term_pattern(x)) as include_hit,
         (select x from unnest(me.title_exclude) x
           where lower(j.title) ~ public.term_pattern(x) limit 1) as exclude_term,
         j.remote and (
           exists (select 1 from unnest(me.remote_allowed_regions) r
                    where lower(coalesce(j.location, '')) ~ public.term_pattern(r))
           -- "Remote" with no place named counts as open to anyone
           or regexp_replace(lower(coalesce(j.location, '')), '\mremote\M|[^a-z]', '', 'g') = ''
         ) as remote_ok,
         exists (select 1 from cities c
                  where lower(coalesce(j.location, '')) like '%' || c.city || '%') as in_city
  from public.job_postings j
  cross join me
  cross join lateral (
    select coalesce(sum(s.weight), 0)::int as score,
           coalesce(array_agg(s.skill order by s.weight desc, s.skill), '{}') as matched
    from skills s
    where lower(j.title || ' ' || coalesce(j.description, '')) ~ s.pat
  ) sk
  where p_max_days is null
     or coalesce(j.posted_date, (j.created_at at time zone 'utc')::date) >= current_date - p_max_days
),
evaluated as (
  select s.*,
    array_remove(array[
      case when cardinality(s.title_include) > 0 and not s.include_hit
           then 'title is not one of your target roles' end,
      case when s.exclude_term is not null
           then format('title contains ''%s''', s.exclude_term) end,
      case when s.max_years_required is not null and s.years_required > s.max_years_required
           then format('asks for %s+ years', s.years_required) end,
      case when s.score < s.min_score
           then format('score below %s', s.min_score) end,
      case when not ((s.n_locations = 0 and not s.open_to_remote) or s.in_city
                     or (s.open_to_remote and s.remote_ok))
           then 'outside your locations' end
    ], null) as why
  from scored s
)
select e.id, e.title, e.company, e.location, e.remote, e.salary, e.url,
       left(e.description, 600), e.posted_date, e.created_at, e.source, e.years_required,
       e.score, e.matched, e.remote_ok, cardinality(e.why) = 0, e.why
from evaluated e
where p_include_ineligible or cardinality(e.why) = 0
order by cardinality(e.why) = 0 desc, e.score desc,
         coalesce(e.posted_date, (e.created_at at time zone 'utc')::date) desc
limit p_limit
$$;
revoke execute on function public.match_jobs(int, boolean, int) from public, anon;
grant execute on function public.match_jobs(int, boolean, int) to authenticated;

-- ---------------------------------------------------------------------------
-- Resume storage: private bucket; each user owns the folder named after their id.
-- ---------------------------------------------------------------------------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('resumes', 'resumes', false, 10485760, array['application/pdf', 'text/plain'])
on conflict (id) do nothing;

create policy "Users read their own resume" on storage.objects for select to authenticated
  using (bucket_id = 'resumes' and (storage.foldername(name))[1] = (select auth.uid())::text);
create policy "Users upload their own resume" on storage.objects for insert to authenticated
  with check (bucket_id = 'resumes' and (storage.foldername(name))[1] = (select auth.uid())::text);
create policy "Users replace their own resume" on storage.objects for update to authenticated
  using (bucket_id = 'resumes' and (storage.foldername(name))[1] = (select auth.uid())::text);
create policy "Users delete their own resume" on storage.objects for delete to authenticated
  using (bucket_id = 'resumes' and (storage.foldername(name))[1] = (select auth.uid())::text);
